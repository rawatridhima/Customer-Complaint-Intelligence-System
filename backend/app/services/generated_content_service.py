"""LLM-generated content for a complaint: summary, suggested resolution and
draft response (FR-19 to FR-25), and the agent's edit-and-approve workflow.

Lifecycle of one complaint's content:

    generated (by the worker, or regenerated by an agent)
      -> optionally edited by the agent       final_response holds the edit,
                                               draft_response keeps the original
      -> approved                              locked: no more edits or regeneration

Only the redacted complaint text is ever sent to the LLM (FR-06, C-03).
"""

import json
import logging
import uuid
from datetime import UTC, datetime

from sqlalchemy.orm import Session

from app.core.exceptions import (
    ConfigurationError,
    InvalidTransitionError,
    LLMUnavailableError,
    NotFoundError,
    ValidationError,
)
from app.core.logging import log_event
from app.models.audit_log import AuditLog
from app.models.complaint import Complaint
from app.models.generated_content import GeneratedContent
from app.repositories.audit_log_repo import AuditLogRepository
from app.repositories.complaint_repo import ComplaintRepository
from app.repositories.generated_content_repo import GeneratedContentRepository
from app.repositories.knowledge_article_repo import KnowledgeArticleRepository
from app.services.llm_service import TONES, Article, LLMService, choose_tone
from app.services.retrieval import rank_articles

logger = logging.getLogger(__name__)


class GeneratedContentService:
    def __init__(self, db: Session, llm: LLMService | None = None) -> None:
        self._complaints = ComplaintRepository(db)
        self._repo = GeneratedContentRepository(db)
        self._articles = KnowledgeArticleRepository(db)
        self._audit = AuditLogRepository(db)
        self._llm = llm or LLMService()

    @property
    def llm_available(self) -> bool:
        return self._llm.available

    # ---- generation ------------------------------------------------------------

    def generate(
        self,
        complaint_id: uuid.UUID,
        tone: str | None = None,
        *,
        allow_fallback: bool = True,
        actor_id: uuid.UUID | None = None,
    ) -> GeneratedContent:
        """Generate (or regenerate) content for a complaint.

        tone: None picks it from sentiment and priority (FR-21); an agent can
        pass one explicitly when regenerating.

        allow_fallback=False makes an LLM failure raise LLMUnavailableError
        instead of saving the template, so the worker can retry first
        (NFR-08) and only fall back on its last attempt.
        """
        complaint = self._complaints.get(complaint_id)
        if complaint is None:
            raise NotFoundError(f"Complaint {complaint_id} not found")
        prediction = complaint.prediction
        if prediction is None:
            raise InvalidTransitionError("The complaint has not been analysed yet")
        if tone is not None and tone not in TONES:
            raise ValidationError(f"Unknown tone '{tone}'. Choose from: {', '.join(TONES)}")

        content = self._repo.get_by_complaint(complaint_id)
        if content is not None and content.approved_at is not None:
            raise InvalidTransitionError("The response is already approved and can no longer change")

        tone = tone or choose_tone(prediction.sentiment_label, prediction.priority_bucket)
        values = (
            self._from_cache(complaint, tone)
            or self._from_llm(complaint, tone, allow_fallback)
        )

        if content is None:
            content = GeneratedContent(complaint_id=complaint_id, **values)
            self._repo.add(content)
        else:
            for key, value in values.items():
                setattr(content, key, value)
            # Regenerating replaces the draft, so any unsaved edit is discarded.
            content.final_response = None
            content.was_edited = False

        if actor_id is not None:
            self._audit.add(AuditLog(
                actor_id=actor_id,
                action="response_regenerated",
                entity_type="complaint",
                entity_id=complaint_id,
                details=json.dumps({"tone": tone, "fallback": values["is_fallback"]}),
            ))
        self._repo.commit()
        return content

    def _from_cache(self, complaint: Complaint, tone: str) -> dict | None:
        """FR-24. Reuse content generated for identical text; no LLM call."""
        cached = self._repo.find_cached(
            complaint.text_hash, self._llm.prompt_version, tone, complaint.complaint_id)
        if cached is None:
            return None
        log_event(logger, "llm_cache_hit", complaint_id=str(complaint.complaint_id),
                  source_complaint_id=str(cached.complaint_id))
        return {
            "summary": cached.summary,
            "suggested_resolution": cached.suggested_resolution,
            "draft_response": cached.draft_response,
            "cited_article_ids": cached.cited_article_ids,
            "prompt_version": cached.prompt_version,
            "llm_model": cached.llm_model,
            "token_count": 0,  # nothing was spent this time
            "tone": tone,
            "is_fallback": False,
            "fallback_reason": None,
        }

    def _from_llm(self, complaint: Complaint, tone: str, allow_fallback: bool) -> dict:
        prediction = complaint.prediction
        candidates = self._articles.list_by_category(prediction.category)
        chosen = rank_articles(complaint.redacted_text, candidates, limit=3)
        labelled = {f"KB-{i}": a for i, a in enumerate(chosen, start=1)}

        try:
            analysis = self._llm.analyse(
                complaint_text=complaint.redacted_text,
                category=prediction.category.value,
                sentiment=prediction.sentiment_label.value,
                priority=prediction.priority_bucket.value,
                articles=[Article(label, a.title, a.body) for label, a in labelled.items()],
            )
            draft, draft_tokens = self._llm.draft_response(
                complaint.redacted_text, analysis.resolution, tone)
        except (LLMUnavailableError, ConfigurationError) as exc:
            if not allow_fallback:
                raise
            log_event(logger, "llm_fallback", complaint_id=str(complaint.complaint_id),
                      reason=exc.message)
            return self._fallback(tone, exc.message)

        log_event(logger, "llm_generated", complaint_id=str(complaint.complaint_id),
                  tone=tone, cited=len(analysis.cited_labels))
        return {
            "summary": analysis.summary,
            "suggested_resolution": analysis.resolution,
            "draft_response": draft,
            "cited_article_ids": [labelled[label].article_id for label in analysis.cited_labels],
            "prompt_version": self._llm.prompt_version,
            "llm_model": analysis.model or self._llm.model,
            "token_count": (analysis.tokens or 0) + (draft_tokens or 0) or None,
            "tone": tone,
            "is_fallback": False,
            "fallback_reason": None,
        }

    def _fallback(self, tone: str, reason: str) -> dict:
        """FR-25. The predefined template, marked for manual handling."""
        return {
            "summary": None,
            "suggested_resolution": None,
            "draft_response": self._llm.fallback_response(),
            "cited_article_ids": None,
            "prompt_version": self._llm.prompt_version,
            "llm_model": None,
            "token_count": None,
            "tone": tone,
            "is_fallback": True,
            "fallback_reason": reason[:255],
        }

    # ---- reading -----------------------------------------------------------------

    def get(self, complaint_id: uuid.UUID) -> GeneratedContent:
        content = self._repo.get_by_complaint(complaint_id)
        if content is None:
            raise NotFoundError(f"No generated content yet for complaint {complaint_id}")
        return content

    def view(self, content: GeneratedContent) -> dict:
        """The API shape: the row plus the titles of the cited articles."""
        articles = self._articles.get_many(content.cited_article_ids or [])
        data = {c.key: getattr(content, c.key) for c in GeneratedContent.__table__.columns}
        data["cited_articles"] = [{"article_id": a.article_id, "title": a.title} for a in articles]
        return data

    # ---- editing and approval (FR-22, FR-23) --------------------------------------

    def save_edit(self, complaint_id: uuid.UUID, text: str) -> GeneratedContent:
        """FR-23. The edit goes in final_response; the generated draft is kept."""
        content = self._editable(complaint_id)
        content.final_response = text
        content.was_edited = text.strip() != (content.draft_response or "").strip()
        self._repo.commit()
        return content

    def approve(
        self,
        complaint_id: uuid.UUID,
        final_response: str,
        approved_by: uuid.UUID,
    ) -> GeneratedContent:
        """FR-22. Nothing is sent to a customer without this step. Records who
        approved and when, and locks the content."""
        content = self._editable(complaint_id)
        content.final_response = final_response
        content.was_edited = final_response.strip() != (content.draft_response or "").strip()
        content.approved_by = approved_by
        content.approved_at = datetime.now(UTC)
        # FR-30: approvals are part of the complaint's audit trail.
        self._audit.add(AuditLog(
            actor_id=approved_by,
            action="response_approved",
            entity_type="complaint",
            entity_id=complaint_id,
            details=json.dumps({"edited": content.was_edited, "fallback": content.is_fallback}),
        ))
        self._repo.commit()
        return content

    def _editable(self, complaint_id: uuid.UUID) -> GeneratedContent:
        content = self.get(complaint_id)
        if content.approved_at is not None:
            raise InvalidTransitionError("The response is already approved and can no longer change")
        return content
